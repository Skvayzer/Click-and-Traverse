"""Ground-projected goal for the guidance field (the "column" goal seed).

The bank's guidance fields (gf) were generated by pf_modular.make_guidance_field_progressive: an arrival-time map
solved in 3-D from a 12 cm ball at the goal point, z = 0.75 m. Every arrow points at that ball, so a body point above
it (head) tilts down and one below it (feet) tilts up, by angles that only depend on the distance to the goal: on
open floor head -17 / feet +24 deg at 1.5 m, -50 / +60 deg at 0.4 m. Together with the CAT success line at x = 1.5 m
(0.35-0.40 m before the ball for a standing robot) the policies learned to stop ~0.4 m before any goal.

The column seed projects the goal onto the ground: the arrival-time map starts from every free voxel within 12 cm
of the goal xy at heights 0.10-1.40 m (the robot perception volume), so near the goal the arrows stay level at every
height. The solve stays 3-D, so obstacles still bend the arrows up or down (beams, hurdles).

The bank itself is hash-pinned (manifest, retention and width-curriculum validators), so the column fields live in a
separate cache: one packed gf per scene, in the bank's own encoding, plus cache.json pinning the bank manifest hash
and the parameters. SceneBank(goal_seed_cache=...) swaps them in at load time.

The robot side is humanoid_navigation cat/wholebody_fields.training_fields(goal_seed='column'), which uses the same
radius, heights and blending.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

SCHEMA = 'cat-goal-seed-cache-v1'
SEED_RADIUS = .12          # pf_modular PFConfig.goal_seed_r
COLUMN_Z = (.10, 1.40)     # heights of the column seed (robot perception volume)
R_PROJ_CELLS = 5.          # tangential blending radius, voxels (pf_modular default)


def column_guidance(occupancy, origin, dx, goal_xy, bunit, sdf, *, radius=SEED_RADIUS, z_range=COLUMN_Z,
                    r_proj_cells=R_PROJ_CELLS):
    """pf_modular.make_guidance_field_progressive with the goal seed projected onto the ground.

    occupancy bool [X, Y, Z]; origin: world position of grid point (0, 0, 0); bunit: unit boundary normals (...,3);
    sdf in metres. Returns unit guidance (...,3) float32 (zero where undefined), as the generator does."""
    import skfmm
    occupancy = np.asarray(occupancy, dtype=bool)
    axes = [float(origin[i]) + np.arange(occupancy.shape[i]) * dx for i in range(3)]
    X, Y, Z = np.meshgrid(*axes, indexing='ij')
    seed = (((X - goal_xy[0]) ** 2 + (Y - goal_xy[1]) ** 2) <= radius ** 2) & (Z >= z_range[0]) & (Z <= z_range[1])
    if not (seed & ~occupancy).any():
        raise ValueError('goal column has no free voxel')
    phi = np.ma.MaskedArray(np.where(seed, -1., 1.), mask=occupancy)
    T_ma = np.ma.asarray(skfmm.distance(phi, dx=dx))
    free = ~np.ma.getmaskarray(T_ma)
    T = T_ma.filled(float(np.max(T_ma[free])) if free.any() else 0.).astype(np.float32)
    g = -np.stack(np.gradient(T, dx, dx, dx, edge_order=2), axis=-1).astype(np.float32)
    g_perp = g - np.sum(g * bunit, axis=-1, keepdims=True) * bunit
    t = np.clip(np.maximum(sdf, 0.) / (r_proj_cells * dx + 1e-9), 0., 1.)
    w = (1. - t * t * (3. - 2. * t))[..., None]
    mix = (1. - w) * g + w * g_perp
    mix[occupancy] = bunit[occupancy]
    mag = np.linalg.norm(mix, axis=-1, keepdims=True)
    return np.where(mag > 1e-9, mix / np.maximum(mag, 1e-9), 0.).astype(np.float32)


def _sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def scene_column_field(directory, record):
    """Column-seed gf for one bank scene, packed as the bank packs gf (int16 octahedral codes + validity bits).
    Occupancy from obs.npy when the scene has it, else SDF <= 0."""
    from .packing.field_packing import pack_direction, unpack_direction, unpack_occupancy, unpack_scalar
    directory = Path(directory); shape = tuple(record['shape'])
    sdf = np.load(directory / 'sdf.npy')
    sdf = unpack_scalar(sdf) if sdf.dtype == np.float16 else np.asarray(sdf, np.float32)
    bf = np.load(directory / 'bf.npy')
    if bf.dtype == np.int16:
        bunit = unpack_direction(bf, np.load(directory / 'bf_valid.npy'), shape)
    else:
        n = np.linalg.norm(bf, axis=-1, keepdims=True); bunit = np.where(n > 1e-9, bf / np.maximum(n, 1e-9), 0.)
    if (directory / 'obs.npy').exists():
        obs = np.load(directory / 'obs.npy')
        occupancy = (unpack_occupancy(obs, shape) if obs.ndim == 1 else obs).astype(bool)
    else:
        occupancy = sdf <= 0.
    gf = column_guidance(occupancy, record['origin'], float(record['dx']), record['goal'][:2], bunit.astype(np.float32), sdf)
    return pack_direction(gf)


def load_cache(cache_dir, manifest_sha256, scene_ids):
    """cache.json for a bank: checks its schema, bank manifest hash, scene set and its own hash."""
    cache_dir = Path(cache_dir)
    meta = json.loads((cache_dir / 'cache.json').read_text())
    expected = meta.pop('cache_sha256')
    actual = hashlib.sha256(json.dumps(meta, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    if meta.get('schema') != SCHEMA or actual != expected:
        raise ValueError(f'goal-seed cache {cache_dir}: schema or hash mismatch')
    if meta['bank_manifest_sha256'] != manifest_sha256:
        raise ValueError(f'goal-seed cache {cache_dir} was built for another bank')
    missing = set(scene_ids) - set(meta['scenes'])
    if missing:
        raise ValueError(f'goal-seed cache {cache_dir} lacks {len(missing)} scenes')
    meta['cache_sha256'] = expected
    return meta
